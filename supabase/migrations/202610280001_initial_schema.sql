create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text check (display_name is null or char_length(btrim(display_name)) between 1 and 80),
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.restaurants (
  id text primary key,
  name text not null check (char_length(btrim(name)) > 0),
  category text not null check (char_length(btrim(category)) > 0),
  address text,
  latitude double precision check (latitude between -90 and 90),
  longitude double precision check (longitude between -180 and 180),
  representative_menu text,
  representative_price integer check (representative_price >= 0),
  opening_hours text,
  photo_url text,
  source_url text,
  verified_at timestamptz,
  verification_status text not null default 'pending'
    constraint restaurants_verification_status_check check (verification_status in ('pending', 'partial', 'verified')),
  is_franchise boolean,
  operating_status text,
  verification_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.menus (
  id bigint generated by default as identity primary key,
  restaurant_id text not null references public.restaurants(id) on delete cascade,
  name text not null check (char_length(btrim(name)) > 0),
  price integer check (price >= 0),
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.reviews (
  id uuid primary key default gen_random_uuid(),
  restaurant_id text not null references public.restaurants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  body text not null check (char_length(btrim(body)) between 1 and 5000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.review_tags (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(btrim(name)) > 0)
);

create table public.review_tag_links (
  review_id uuid not null references public.reviews(id) on delete cascade,
  tag_id bigint not null references public.review_tags(id) on delete cascade,
  primary key (review_id, tag_id)
);

create table public.favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  restaurant_id text not null references public.restaurants(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, restaurant_id)
);

-- Client timestamps never determine which review is the latest.
create function public.set_row_timestamps() returns trigger
language plpgsql set search_path = '' as $$
begin
  if TG_OP = 'INSERT' then
    NEW.created_at := clock_timestamp();
  else
    NEW.created_at := OLD.created_at;
  end if;
  NEW.updated_at := clock_timestamp();
  return NEW;
end;
$$;

create function public.preserve_review_identity() returns trigger
language plpgsql set search_path = '' as $$
begin
  if NEW.id is distinct from OLD.id
    or NEW.user_id is distinct from OLD.user_id
    or NEW.restaurant_id is distinct from OLD.restaurant_id
    or NEW.created_at is distinct from OLD.created_at then
    raise exception 'Review identity and creation time are immutable';
  end if;
  return NEW;
end;
$$;

create trigger reviews_identity before update on public.reviews
  for each row execute function public.preserve_review_identity();
create trigger reviews_timestamps before insert or update on public.reviews
  for each row execute function public.set_row_timestamps();
create trigger profiles_timestamps before insert or update on public.profiles
