create view public.restaurant_ratings with (security_invoker = true) as
with latest as (
  select distinct on (restaurant_id, user_id) restaurant_id, user_id, rating
  from public.reviews
  order by restaurant_id, user_id, created_at desc, id desc
), ratings as (
  select restaurant_id, avg(rating) as average_rating, count(*) as reviewer_count
  from latest group by restaurant_id
), totals as (
  select restaurant_id, count(*) as review_count from public.reviews group by restaurant_id
)
select r.id as restaurant_id, ratings.average_rating,
  coalesce(ratings.reviewer_count, 0::bigint) as reviewer_count,
  coalesce(totals.review_count, 0::bigint) as review_count
from public.restaurants r
left join ratings on ratings.restaurant_id = r.id
left join totals on totals.restaurant_id = r.id;

create view public.restaurant_catalog with (security_invoker = true) as
select r.*, s.average_rating, s.reviewer_count, s.review_count
from public.restaurants r
join public.restaurant_ratings s on s.restaurant_id = r.id;

